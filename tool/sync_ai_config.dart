// Skill validation
// ---------------------------------------------------------------------------

final _skillNamePattern = RegExp(r'^[a-z0-9]+(-[a-z0-9]+)*$');

/// Validates a skill's `SKILL.md` frontmatter against the Agent Skills
/// naming spec that OpenCode enforces (silently skipping a non-conforming
/// skill) and Pi warns on — see ai/README.md's harness-support table.
/// Public so `tool/test/` can exercise it directly. Returns one
/// human-readable error string per violation; empty means valid.
List<String> skillValidationErrors({
  required String folderName,
  required String skillMdContent,
}) {
  YamlMap? frontmatter;
  try {
    frontmatter = _extractFrontmatter(skillMdContent);
  } on YamlException catch (e) {
    // A skill author's YAML that fails to parse (an unquoted colon in a
    // description, a duplicate key, ...) must produce one validation error
    // for that skill, not crash the whole generator — every other skill
    // still needs to render. See `main`'s skill-validation loop, which
    // collects errors across all skills before failing.
    return ['malformed YAML frontmatter: ${e.message}'];
  }
  if (frontmatter == null) {
    return ['missing or malformed YAML frontmatter (a leading `---` block)'];
  }

  final errors = <String>[];
  final name = frontmatter['name']?.toString() ?? '';
  final description = frontmatter['description']?.toString() ?? '';

  if (!_skillNamePattern.hasMatch(name)) {
    errors.add(
      'name "$name" must match ${_skillNamePattern.pattern} '
      '(lowercase letters, digits and single hyphens only)',
    );
  }
  if (name.length > 64) {
    errors.add('name "$name" is ${name.length} characters long, must be 64 or fewer');
  }
  if (name != folderName) {
    errors.add('name "$name" must match its folder name "$folderName"');
  }
  if (description.isEmpty) {
    errors.add('description must not be empty');
  } else if (description.length > 1024) {
    errors.add('description is ${description.length} characters long, must be 1024 or fewer');
  }
  return errors;
}

/// Parses the YAML block between a file's opening and closing `---` lines.
/// Returns null if the file doesn't start with `---` on its literal first
/// line, or the block never closes — see `_insertNoticeIntoFrontmatter`'s
/// doc comment for why frontmatter parsers are strict about the opening
/// `---` being the first line.
YamlMap? _extractFrontmatter(String content) {
  final lines = content.split('\n');
  if (lines.isEmpty || lines.first.trim() != '---') return null;
  final end = lines.indexWhere((line) => line.trim() == '---', 1);
  if (end == -1) return null;
  final doc = loadYaml(lines.sublist(1, end).join('\n'));
  return doc is YamlMap ? doc : null;
}

String _renderCoreRules() {
  return '''
---
