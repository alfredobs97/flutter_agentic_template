/// Renders [notice] (a multi-line plain-text notice) as YAML comment lines
/// (`# ...`), one per input line — safe to place as the first lines
/// *inside* a frontmatter block, right after the opening `---`. Never place
/// a notice before the opening `---`: a frontmatter parser only recognizes
/// the block when `---` is the literal first line of the file, so anything
/// — even an HTML comment — placed before it silently makes every field in
/// the block invisible to that parser. This is exactly the bug a
/// senior-reviewer audit caught in an earlier version of this file.
String _yamlCommentBlock(String notice) {
  return notice.split('\n').map((line) => '# $line').join('\n');
}

/// Same job as [_yamlCommentBlock], but with `//` line comments instead of
/// `#` — for JSONC output (`renderOpenCodeConfig`). JSONC (like JSON5) only
/// recognizes `//` and `/* */` as comment syntax; a `#`-prefixed line there
/// is a parse error, not just an unrecognized comment.
String _jsoncCommentBlock(String notice) {
  return notice.split('\n').map((line) => '// $line').join('\n');
}

/// Inserts [notice] as a YAML comment block just inside [source]'s existing
/// opening `---`, preserving it as the file's literal first line. Falls
/// back to a leading HTML comment if [source] has no frontmatter to begin
/// with (defensive — every current caller's source does have one).
String _insertNoticeIntoFrontmatter(String source, String notice) {
  final lines = source.split('\n');
  if (lines.isEmpty || lines.first.trim() != '---') {
    return '<!-- ${notice.replaceAll('\n', ' ')} -->\n\n$source';
  }
  return [lines.first, _yamlCommentBlock(notice), ...lines.skip(1)].join('\n');
}

/// Folds a plain-text description onto one YAML scalar line, safely, by
/// using a single-quoted YAML string (single quotes need only '' escaping
/// for an embedded '). Avoids the ambiguity of an unquoted scalar containing
/// a colon.
String _yamlFold(String text) {
  final singleLine = text.replaceAll('\n', ' ').replaceAll(RegExp(' +'), ' ').trim();
  return "'${singleLine.replaceAll("'", "''")}'";
}

/// Renders a TOML basic string. Used for short, single-line values only.
//
// The replacement patterns below are deliberately backslash-escape
// sequences (not raw strings) — mixing raw and non-raw literals in a
// string-escaping routine like this one would make the actual characters
// being matched/inserted harder to see at a glance, not easier.
String _tomlString(String value) {
  final escaped = value
      // Search pattern is a literal backslash; a raw string here would
      // read as an *empty* escape sequence to a skimming reader.
      // ignore: use_raw_strings
      .replaceAll('\\', '\\\\')
      // Same reasoning: '\"' below is the two-character replacement
      // (backslash + quote), clearer written as an escape than raw.
      // ignore: use_raw_strings
      .replaceAll('"', '\\"')
      // Replacement is the two-character escape sequence '\n', not a
      // literal newline — clearer spelled out than as a raw string.
      // ignore: use_raw_strings
      .replaceAll('\n', '\\n')
      // Same reasoning for the tab escape.
      // ignore: use_raw_strings
      .replaceAll('\t', '\\t');
  return '"$escaped"';
}

/// Renders a TOML multi-line literal string (`'''...'''`), which preserves
/// the text completely raw — no escaping needed for quotes, backslashes or
/// newlines. Falls back to an escaped basic string in the (very unlikely)
/// case the content itself contains a `'''` sequence, since that would
/// otherwise prematurely close the literal string.
String _tomlMultiline(String value) {
  if (!value.contains("'''")) {
    return "'''\n$value\n'''";
  }
  return _tomlString(value);
}
