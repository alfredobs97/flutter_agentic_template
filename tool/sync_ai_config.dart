// Renders every per-tool AI configuration file (Claude Code, OpenAI Codex,
// Google Antigravity, OpenCode) from the canonical, tool-neutral source in
// `ai/` plus the skill files in `.agents/skills/`. See `ai/README.md` for
// the full rationale and the exact schema of `ai/agents/*.yaml` and
// `ai/mcp.yaml`.
//
// Pi is deliberately NOT rendered here: it has no subagent or MCP concept
// to target (see ai/README.md), and its formatter hook
// (`.pi/extensions/dart-format.ts`) is hand-written, the same way
// `tool/hooks/format_changed.dart` is hand-written for Claude Code's
// PostToolUse hook rather than generated — both are small enough that a
// generator would add more indirection than it saves.
//
// Usage:
//   fvm dart run tool/sync_ai_config.dart            # write every generated file
//   fvm dart run tool/sync_ai_config.dart --check     # exit 1 if any generated
//                                                      # file would change
//
// `--check` is what `tool/quality_gate.dart` runs — it never writes. A
// human/agent who has changed anything under `ai/` or `.agents/skills/`
// runs the no-flag form to regenerate, then commits the result.
//
// Before rendering anything, every `.agents/skills/*/SKILL.md` is validated
// against the Agent Skills naming spec (see `skillValidationErrors` below)
// — OpenCode silently drops a skill whose `name` fails that regex, and Pi
// only warns, so this check is what catches the mistake at sync time
// instead of at "why isn't my skill showing up" debugging time.
//
// KNOWN LIMITATION: this script re-renders every path it knows how to
// produce today; it does not detect a file that was generated by a past
// version of this script for an agent/skill that has since been deleted
// (no manifest of "previously generated paths" is kept). If you delete an
// `ai/agents/*.yaml` file, manually remove its old `.claude/agents/*.md` /
// `.codex/agents/*.toml` / `.agents/agents/*.md` / `.opencode/agents/*.md`
// counterparts too.
import 'dart:convert';
import 'dart:io';

import 'package:yaml/yaml.dart';

const _generatedNotice =
    'GENERATED FILE — DO NOT EDIT.\n'
    'Source: run `fvm dart run tool/sync_ai_config.dart` after editing the\n'
    'files under ai/ or .agents/skills/. See ai/README.md.';

void main(List<String> args) {
  final checkOnly = args.contains('--check');
  final repoRoot = Directory.current;

  final agents = _loadAgents(Directory('${repoRoot.path}/ai/agents'));
  final mcp = _loadMcp(File('${repoRoot.path}/ai/mcp.yaml'));
  final skillNames = _listSkillNames(Directory('${repoRoot.path}/.agents/skills'));
  final reviewWorkflow = File('${repoRoot.path}/ai/workflows/review.md');

  final skillErrors = <String>[];
  for (final name in skillNames) {
    final skillFile = File('${repoRoot.path}/.agents/skills/$name/SKILL.md');
    if (!skillFile.existsSync()) {
      skillErrors.add('$name: missing SKILL.md');
      continue;
    }
    for (final error in skillValidationErrors(
      folderName: name,
      skillMdContent: skillFile.readAsStringSync(),
    )) {
      skillErrors.add('$name: $error');
    }
  }
  if (skillErrors.isNotEmpty) {
    stderr.writeln(
      'Invalid skill frontmatter (violates the Agent Skills naming spec that '
      "OpenCode enforces and Pi warns on — see ai/README.md's harness-support table):",
    );
    for (final error in skillErrors) {
      stderr.writeln('  - $error');
    }
    exitCode = 1;
    return;
  }

  final outputs = <String, String>{};

  for (final agent in agents) {
    outputs['.claude/agents/${agent.name}.md'] = _renderClaudeAgent(agent);
    outputs['.codex/agents/${agent.name}.toml'] = _renderCodexAgent(agent);
    outputs['.agents/agents/${agent.name}.md'] = _renderAntigravityAgent(agent);
    outputs['.opencode/agents/${agent.name}.md'] = renderOpenCodeAgent(agent);
  }

  outputs['.mcp.json'] = _renderClaudeMcp(mcp);
  outputs['.codex/config.toml'] = _renderCodexConfig(mcp);
  outputs['.agents/mcp_config.json'] = _renderAntigravityMcp(mcp);
  outputs['opencode.jsonc'] = renderOpenCodeConfig(mcp);
  outputs['.opencode/.gitignore'] = renderOpenCodeGitignore();

  outputs['.claude/settings.json'] = _renderClaudeSettings(mcp);
  outputs['.agents/rules/00-core.md'] = _renderCoreRules();

  if (reviewWorkflow.existsSync()) {
    outputs['.agents/workflows/code-review.md'] = _renderAntigravityWorkflow(
      reviewWorkflow.readAsStringSync(),
    );
  }

  // Skill copies: everything under .agents/skills/<name>/ is mirrored
  // verbatim into .claude/skills/<name>/ (Claude Code doesn't read
  // .agents/skills — Codex, Antigravity, OpenCode and Pi all do, natively,
  // so none of those four need a copy).
  final skillCopies = <String, String>{};
  for (final name in skillNames) {
    final sourceDir = Directory('${repoRoot.path}/.agents/skills/$name');
    for (final entity in sourceDir.listSync(recursive: true)) {
      if (entity is! File) continue;
      final relative = entity.path.substring(sourceDir.path.length + 1);
      skillCopies['.claude/skills/$name/$relative'] = entity.readAsStringSync();
    }
  }

  final allOutputs = {...outputs, ...skillCopies};

  if (checkOnly) {
    final drift = <String>[];
    allOutputs.forEach((relativePath, expectedContent) {
      final file = File('${repoRoot.path}/$relativePath');
      if (!file.existsSync()) {
        drift.add('missing: $relativePath');
        return;
      }
      if (file.readAsStringSync() != expectedContent) {
        drift.add('out of date: $relativePath');
      }
    });

    if (drift.isEmpty) {
      stdout.writeln('AI config is in sync (${allOutputs.length} generated files checked).');
      exitCode = 0;
    } else {
      stderr
        ..writeln('AI config is OUT OF SYNC. Run:')
        ..writeln('  fvm dart run tool/sync_ai_config.dart')
        ..writeln('to regenerate, then commit the result. Drifted files:');
      for (final line in drift) {
        stderr.writeln('  - $line');
      }
      exitCode = 1;
    }
    return;
  }

  var written = 0;
  allOutputs.forEach((relativePath, content) {
    final file = File('${repoRoot.path}/$relativePath');
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(content);
    written++;
  });
  stdout.writeln('Wrote $written generated AI config file(s).');
}

// ---------------------------------------------------------------------------
// Agent definitions (ai/agents/*.yaml)
// ---------------------------------------------------------------------------

class AgentDef {
  AgentDef({
    required this.name,
    required this.description,
    required this.access,
    required this.tier,
    required this.skills,
    required this.prompt,
  });

  final String name;
  final String description;
  final String access; // 'read-only' | 'run-only' | 'write'
  final String tier; // 'deep' | 'standard' | 'fast'
  final List<String> skills;
  final String prompt;
}

List<AgentDef> _loadAgents(Directory dir) {
  if (!dir.existsSync()) return const [];
  final files = dir.listSync().whereType<File>().where((f) => f.path.endsWith('.yaml')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  return files.map((file) {
    final doc = loadYaml(file.readAsStringSync()) as YamlMap;
    final skillsNode = doc['skills'];
    final skills = skillsNode is YamlList
        ? skillsNode.map((e) => e.toString()).toList()
        : <String>[];
    return AgentDef(
      name: (doc['name'] as String).trim(),
      description: (doc['description'] as String).trim(),
      access: (doc['access'] as String).trim(),
      tier: (doc['tier'] as String).trim(),
      skills: skills,
      prompt: (doc['prompt'] as String).trimRight(),
    );
  }).toList();
}

/// True for an access level that never gets a file-editing tool
/// (`read-only` and `run-only` both render the same restricted Claude/
/// Antigravity tool list — they differ only in Codex's sandbox_mode, where
/// `run-only` still needs filesystem writes for build/test output; see
/// ai/README.md's access mapping table).
bool _hasNoEditingTools(String access) => access == 'read-only' || access == 'run-only';

String _claudeModelFor(String tier) => switch (tier) {
  'deep' => 'opus',
  'standard' => 'sonnet',
  'fast' => 'haiku',
  _ => throw ArgumentError('Unknown tier "$tier" — expected deep|standard|fast'),
};

String _antigravityModelFor(String tier) => switch (tier) {
  'deep' => 'pro',
  'standard' || 'fast' => 'flash',
  _ => throw ArgumentError('Unknown tier "$tier" — expected deep|standard|fast'),
};

String? _codexReasoningEffortFor(String tier) => switch (tier) {
  'deep' => 'high',
  'fast' => 'low',
  'standard' => null, // account default
  _ => throw ArgumentError('Unknown tier "$tier" — expected deep|standard|fast'),
};

// ---------------------------------------------------------------------------
// MCP servers (ai/mcp.yaml)
// ---------------------------------------------------------------------------

class McpServer {
  McpServer({
    required this.name,
    required this.description,
    required this.command,
    required this.args,
    required this.envVarNames,
    required this.enabledByDefault,
  });

  final String name;
  final String description;
  final String command;
  final List<String> args;
  final List<String> envVarNames;
  final bool enabledByDefault;
}

List<McpServer> _loadMcp(File file) {
  if (!file.existsSync()) return const [];
  final doc = loadYaml(file.readAsStringSync()) as YamlMap;
  final servers = doc['servers'] as YamlMap? ?? YamlMap();
  return servers.entries.map((entry) {
    final name = entry.key.toString();
    final value = entry.value as YamlMap;
    final argsNode = value['args'];
    final envNode = value['env'];
    return McpServer(
      name: name,
      description: (value['description'] as String? ?? '').trim(),
      command: (value['command'] as String).trim(),
      args: argsNode is YamlList ? argsNode.map((e) => e.toString()).toList() : <String>[],
      envVarNames: envNode is YamlList ? envNode.map((e) => e.toString()).toList() : <String>[],
      enabledByDefault: value['enabled_by_default'] as bool? ?? false,
    );
  }).toList();
}

// ---------------------------------------------------------------------------
// Skills
// ---------------------------------------------------------------------------

List<String> _listSkillNames(Directory dir) {
  if (!dir.existsSync()) return const [];
  return dir
      .listSync()
      .whereType<Directory>()
      .map((d) => d.path.split(Platform.pathSeparator).last)
      .toList()
    ..sort();
}

// ---------------------------------------------------------------------------
// Claude Code rendering
// ---------------------------------------------------------------------------

String _renderClaudeAgent(AgentDef agent) {
  final buffer = StringBuffer()
    ..writeln('---')
    ..writeln(_yamlCommentBlock(_generatedNotice))
    ..writeln('name: ${agent.name}')
    ..writeln('description: ${_yamlFold(agent.description)}');
  if (_hasNoEditingTools(agent.access)) {
    buffer.writeln('tools: Read, Grep, Glob, Bash');
  }
  // access == 'write' omits `tools:` entirely, which means "inherit every
  // tool the parent session has" — see ai/README.md's access mapping table.
  buffer.writeln('model: ${_claudeModelFor(agent.tier)}');
  if (agent.skills.isNotEmpty) {
    buffer.writeln('skills: [${agent.skills.join(', ')}]');
  }
  buffer
    ..writeln('---')
    ..writeln()
    ..writeln(agent.prompt);
  return buffer.toString();
}

String _renderClaudeMcp(List<McpServer> servers) {
  // No per-server `disabled` key here: Claude Code does not read one from
  // project `.mcp.json` (confirmed against current Claude Code docs/issue
  // tracker — a feature request for exactly this was closed as not
  // implemented). The only thing that actually turns a project MCP server
  // off by default is `.claude/settings.json`'s `disabledMcpjsonServers`,
  // rendered by `_renderClaudeSettings` below — every server is listed here
  // unconditionally and disabled, if at all, from that file instead.
  final map = {
    'mcpServers': {
      for (final server in servers)
        server.name: {
          'command': server.command,
          if (server.args.isNotEmpty) 'args': server.args,
          if (server.envVarNames.isNotEmpty)
            'env': {for (final v in server.envVarNames) v: '\${$v}'},
        },
    },
  };
  return '${const JsonEncoder.withIndent('  ').convert(map)}\n';
}

String _renderClaudeSettings(List<McpServer> servers) {
  final disabledServers = servers.where((s) => !s.enabledByDefault).map((s) => s.name).toList();
  final map = {
    r'$schema': 'https://json.schemastore.org/claude-code-settings.json',
    'hooks': {
      'PostToolUse': [
        {
          'matcher': 'Edit|Write',
          'hooks': [
            {
              'type': 'command',
              'command': r'fvm dart run "${CLAUDE_PROJECT_DIR}/tool/hooks/format_changed.dart"',
            },
          ],
        },
      ],
    },
    // This is the field Claude Code actually reads to turn a project MCP
    // server off by default — see the comment on `_renderClaudeMcp` above.
    if (disabledServers.isNotEmpty) 'disabledMcpjsonServers': disabledServers,
  };
  return '${const JsonEncoder.withIndent('  ').convert(map)}\n';
}

// ---------------------------------------------------------------------------
// Codex rendering
// ---------------------------------------------------------------------------

String _renderCodexAgent(AgentDef agent) {
  final buffer = StringBuffer()
    ..writeln('# $_generatedNotice'.replaceAll('\n', '\n# '))
    ..writeln('name = ${_tomlString(agent.name)}')
    ..writeln('description = ${_tomlMultiline(agent.description)}');
  final effort = _codexReasoningEffortFor(agent.tier);
  if (effort != null) buffer.writeln('model_reasoning_effort = ${_tomlString(effort)}');
  // Codex's sandbox_mode is an OS-level filesystem restriction, not just a
  // missing-editing-tool one — "read-only" blocks every write a subprocess
  // makes too. `run-only` needs `workspace-write` so a command like
  // `flutter test` can still write its build/cache output; see
  // ai/README.md's access mapping table for why this differs from Claude
  // and Antigravity, where read-only vs. run-only render identically.
  switch (agent.access) {
    case 'read-only':
      buffer.writeln('sandbox_mode = "read-only"');
    case 'run-only':
      buffer.writeln('sandbox_mode = "workspace-write"');
    case 'write':
      break; // Codex's own default sandbox already permits this.
    default:
      throw ArgumentError(
        'Unknown access "${agent.access}" — expected read-only|run-only|write',
      );
  }
  buffer.writeln('developer_instructions = ${_tomlMultiline(agent.prompt)}');
  return buffer.toString();
}

String _renderCodexConfig(List<McpServer> servers) {
  final buffer = StringBuffer()
    ..writeln('# $_generatedNotice'.replaceAll('\n', '\n# '))
    ..writeln()
    ..writeln('[agents]')
    ..writeln('enabled = true')
    ..writeln();
  for (final server in servers) {
    buffer
      ..writeln('[mcp_servers.${server.name}]')
      ..writeln('command = ${_tomlString(server.command)}');
    if (server.args.isNotEmpty) {
      final args = server.args.map(_tomlString).join(', ');
      buffer.writeln('args = [$args]');
    }
    if (server.envVarNames.isNotEmpty) {
      final vars = server.envVarNames.map(_tomlString).join(', ');
      buffer.writeln('env_vars = [$vars]');
    }
    // Codex's actual on/off switch is this `enabled` field, not the
    // server's presence/absence in the file — a table with no `enabled`
    // line is treated as enabled, so a comment alone (the previous version
    // of this function) did NOT disable anything: Codex would still try to
    // launch it. See ai/README.md and the GitHub issue confirming `enabled`
    // is the real field name (openai/codex#16439 discussion).
    buffer.writeln('enabled = ${server.enabledByDefault}');
    if (!server.enabledByDefault) {
      buffer
        ..writeln('# Disabled by default — see ai/mcp.yaml. Set enabled = true above')
        ..writeln('# once you have credentials configured.');
    }
    buffer.writeln();
  }
  return buffer.toString();
}

// ---------------------------------------------------------------------------
// Antigravity rendering
// ---------------------------------------------------------------------------

String _renderAntigravityAgent(AgentDef agent) {
  const readOnlyTools = ['view_file', 'grep_search', 'run_command'];
  const writeTools = ['view_file', 'grep_search', 'run_command', 'write_file', 'edit_file'];
  // `run_command` is already in readOnlyTools, so run-only and read-only
  // render identically here — see ai/README.md's access mapping table.
  final tools = agent.access == 'write' ? writeTools : readOnlyTools;

  final buffer = StringBuffer()
    ..writeln('---')
    ..writeln(_yamlCommentBlock(_generatedNotice))
    ..writeln('name: ${agent.name}')
    ..writeln('description: ${_yamlFold(agent.description)}')
    ..writeln('tools: [${tools.join(', ')}]')
    ..writeln('model: ${_antigravityModelFor(agent.tier)}')
    ..writeln('subagent: true');
  if (agent.skills.isNotEmpty) {
    buffer.writeln('skills: [${agent.skills.join(', ')}]');
  }
  buffer
    ..writeln('---')
    ..writeln()
    ..writeln(agent.prompt);
  return buffer.toString();
}

String _renderAntigravityMcp(List<McpServer> servers) {
  final map = {
    'mcpServers': {
      for (final server in servers)
        server.name: {
          'command': server.command,
          if (server.args.isNotEmpty) 'args': server.args,
          if (server.envVarNames.isNotEmpty)
            'env': {for (final v in server.envVarNames) v: '\${$v}'},
          'disabled': !server.enabledByDefault,
        },
    },
  };
  return '${const JsonEncoder.withIndent('  ').convert(map)}\n';
}

