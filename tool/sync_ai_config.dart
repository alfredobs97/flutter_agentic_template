/// [reviewWorkflowSource] already starts with its own YAML frontmatter
/// (`---` ... `---`) — the notice is inserted as comment lines just inside
/// that opening `---`, not prepended before it. A frontmatter parser only
/// recognizes the block when `---` is the literal first line of the file;
/// putting anything (even an HTML comment) before it makes every field in
/// the block invisible to that parser.
String _renderAntigravityWorkflow(String reviewWorkflowSource) {
  const notice =
      '$_generatedNotice\nSource: ai/workflows/review.md — edit that file, not this one.';
  return _insertNoticeIntoFrontmatter(reviewWorkflowSource, notice);
}

