/// OpenCode's per-agent `permission` block, keyed off the same `access`
/// levels used for Claude/Codex/Antigravity (public so `tool/test/` can
/// assert the mapping per level — see ai/README.md's access mapping table).
///
/// `read-only`/`run-only` deny `edit` the same way Claude/Antigravity never
/// give those agents an editing tool in the first place. Every level also
/// denies `task` — OpenCode's name for subagent dispatch — because each
/// agent's own prompt already says "do NOT delegate further" (see
/// `ai/agents/*.yaml`); this makes that rule structural instead of
/// instruction-only, the same reasoning `ai/README.md` gives for Codex's
/// `sandbox_mode`. No `model` is set: tiers (`deep`/`standard`/`fast`) have
/// no OpenCode mapping today, so every agent uses the session's own model —
/// see ai/README.md.
Map<String, String> openCodePermissionFor(String access) {
  switch (access) {
    case 'read-only':
    case 'run-only':
      return {'edit': 'deny', 'task': 'deny', 'webfetch': 'deny'};
    case 'write':
      return {'task': 'deny'};
    default:
      throw ArgumentError(
        'Unknown access "$access" — expected read-only|run-only|write',
      );
  }
}

String renderOpenCodeAgent(AgentDef agent) {
  final permission = openCodePermissionFor(agent.access);
  final buffer = StringBuffer()
    ..writeln('---')
    ..writeln(_yamlCommentBlock(_generatedNotice))
    ..writeln('name: ${agent.name}')
    ..writeln('description: ${_yamlFold(agent.description)}')
    ..writeln('mode: subagent')
    ..writeln('permission:');
  for (final entry in permission.entries) {
    buffer.writeln('  ${entry.key}: ${entry.value}');
  }
  buffer
    ..writeln('---')
    ..writeln()
    ..writeln(agent.prompt);
  return buffer.toString();
}

/// `opencode.jsonc` — JSONC (not plain JSON) specifically so the generated
/// notice can be a comment instead of a fake config key; OpenCode's own
/// config loader accepts either extension/syntax. Built by hand rather than
/// through `JsonEncoder`, the same choice `_renderCodexConfig` makes for
/// TOML, because `JsonEncoder` has no way to emit a comment.
///
/// The notice is rendered with `//` line comments, NOT `_yamlCommentBlock`'s
/// `#` — JSONC (like JSON5) only recognizes `//` and `/* */` as comment
/// syntax; a `#`-prefixed line is a parse error, which would make OpenCode
/// reject this entire file (MCP servers and the formatter included) instead
/// of just failing to see a comment.
String renderOpenCodeConfig(List<McpServer> servers) {
  final buffer = StringBuffer()
    ..writeln('{')
    ..writeln('  ${_jsoncCommentBlock(_generatedNotice).replaceAll('\n', '\n  ')}')
    ..writeln(r'  "$schema": "https://opencode.ai/config.json",')
    ..writeln('  "mcp": {');
  for (var i = 0; i < servers.length; i++) {
    final server = servers[i];
    final trailingComma = i == servers.length - 1 ? '' : ',';
    final command = [server.command, ...server.args].map(jsonEncode).join(', ');
    buffer
      ..writeln('    ${jsonEncode(server.name)}: {')
      ..writeln('      "type": "local",')
      ..writeln('      "command": [$command],');
    if (server.envVarNames.isNotEmpty) {
      final environment = server.envVarNames
          .map((v) => '${jsonEncode(v)}: ${jsonEncode('{env:$v}')}')
          .join(', ');
      buffer.writeln('      "environment": {$environment},');
    }
    buffer
      ..writeln('      "enabled": ${server.enabledByDefault}')
      ..writeln('    }$trailingComma');
  }
  buffer
    ..writeln('  },')
    // Runs `dart format` at this repo's 100-column width (not the
    // 80-column default — see the flutter-fvm skill) through `fvm`, the
    // same command tool/hooks/format_changed.dart runs for Claude Code.
    ..writeln('  "formatter": {')
    ..writeln('    "dart": {')
    ..writeln(r'      "command": ["fvm", "dart", "format", "-l", "100", "$FILE"],')
    ..writeln('      "extensions": [".dart"]')
    ..writeln('    }')
    ..writeln('  }')
    ..writeln('}');
  return buffer.toString();
}

/// Mirrors upstream OpenCode's own `.opencode/.gitignore` (node_modules and
/// the package manifests/lockfiles OpenCode generates itself when a project
/// plugin declares npm dependencies) — see ai/README.md.
String renderOpenCodeGitignore() {
  return '${_yamlCommentBlock(_generatedNotice)}\n'
      'node_modules\n'
      'package.json\n'
      'bun.lock\n'
      'package-lock.json\n';
}

